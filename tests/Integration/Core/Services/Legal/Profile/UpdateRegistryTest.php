<?php

namespace Tests\Integration\Core\Services\Legal\Profile;

use App\Core\Entities\EntityNotFoundException;
use App\Core\Entities\User\Legal\Legal;
use App\Core\Entities\User\Legal\ValueObjects\RegistryTemplate;
use App\Core\Services\LegalProfileService;
use PHPUnit\Framework\Attributes\CoversMethod;
use Tests\TestCase;

#[CoversMethod(LegalProfileService::class, 'updateRegistryTemplate')]
class UpdateRegistryTest extends TestCase
{
    private LegalProfileService $service;

    protected function setUp(): void
    {
        parent::setUp(); // TODO: Change the autogenerated stub

        $this->service = app(LegalProfileService::class);
    }

    /**
     * @throws \Throwable
     */
    public function testInvalidLegalId()
    {
        $this->expectException(EntityNotFoundException::class);
        $this->expectExceptionMessage('Юр.лицо не найдено.');

        $this->service->updateRegistryTemplate(999, new RegistryTemplate('template'));
    }

    /**
     * @throws \Throwable
     */
    public function testSuccess()
    {
        $legal = Legal::factory()->withProfile()->create();

        $this->service->updateRegistryTemplate(
            $legal->id,
            new RegistryTemplate($template = 'template')
        );
        $legal->refresh();

        $this->assertEquals($template, $legal->profile->registry_template);
    }
}
