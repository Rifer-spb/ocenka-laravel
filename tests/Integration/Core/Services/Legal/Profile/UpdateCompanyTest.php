use Tests\TestCase;

class UpdateCompanyTest extends TestCase
{
    private LegalProfileService $service;

    protected function setUp(): void
    {
        parent::setUp(); // TODO: Change the autogenerated stub

        $this->service = app(LegalProfileService::class);
    }

    /**
     * @throws \Throwable
     */
    public function testInvalidLegalId()
    {
        $type = LegalType::factory()->create();

        $company = new Company(
            '',
            '',
            '',
            '',
            '',
            1234567890,
            1234567890,
            1234567890,
        );

        $this->expectException(EntityNotFoundException::class);
        $this->expectExceptionMessage('Юр.лицо не найдено.');

        $this->service->updateCompany(999, $type->id, $company);
    }
}
