<?php

namespace Tests\Integration\Core\Services\Notary;

use App\Core\Entities\EntityNotFoundException;
use App\Core\Entities\Notary\Notary;
use App\Core\Entities\Notary\NotaryUpdateData;
use App\Core\Services\NotaryService;
use App\Core\ValueObjects\Email;
use App\Core\ValueObjects\Site;
use PHPUnit\Framework\Attributes\CoversMethod;
use Tests\TestCase;

#[CoversMethod(NotaryService::class, 'update')]
class UpdateTest extends TestCase
{
    private NotaryService $service;

    protected function setUp(): void
    {
        parent::setUp(); // TODO: Change the autogenerated stub

        $this->service = app(NotaryService::class);
    }

    /**
     * @throws \Throwable
     */
    public function testInvalidNotaryId()
    {
        $this->expectException(EntityNotFoundException::class);
        $this->expectExceptionMessage('Нотариус не найден.');

        $this->service->update(1, new NotaryUpdateData(
            [],
            null,
            null,
            null
        ));
    }

    /**
     * @throws \Throwable
     */
    public function testSuccessWithFilled()
    {
        $notary = Notary::factory()->create();

        $this->service->update(1, new NotaryUpdateData(
            [new Email($email = 'test@test.com')],
            new Site($site = 'https://example.com'),
            $useDigitalReport = true,
            $comment = 'comment'
        ));
        $notary->refresh();

        $this->assertCount(1, $notary->emails);
        $this->assertEquals($email, $notary->emails[0]->email);
        $this->assertEquals($site, $notary->site);
        $this->assertEquals($useDigitalReport, $notary->use_digital_report);
        $this->assertEquals($comment, $notary->comment);
    }

    /**
     * @throws \Throwable
     */
    public function testSuccessWithEmpty()
    {
        $notary = Notary::factory()
            ->withEmail('test@test.com')
            ->create([
                'site' => $site = 'https://example.com',
                'use_digital_report' => $useDigitalReport = true,
                'comment' => 'comment'
            ]);

        $this->service->update(1, new NotaryUpdateData(
            [],
            null,
            null,
            null,
        ));
        $notary->refresh();

        $this->assertCount(0, $notary->emails);
        $this->assertNull($notary->site);
        $this->assertNull($notary->use_digital_report);
        $this->assertNull($notary->comment);
    }
}
