<?php

namespace Integration\Core\Services;

use App\Core\Models\Invite\ForWho;
use App\Core\Models\User\Legal\Legal;
use App\Core\Models\User\Phys\Phys;
use App\Core\Models\User\ValueObjects\Password;
use App\Core\Services\InviteService;
use App\Core\ValueObjects\Email;
use App\Manager\Jobs\Invite\SendInviteMailJob;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Queue;
use Illuminate\Support\Facades\Redis;
use Tests\TestCase;

class InviteCreateTest extends TestCase
{
    private InviteService $service;

    protected function setUp(): void
    {
        parent::setUp(); // TODO: Change the autogenerated stub

        $this->service = app(InviteService::class);
    }

    public function testSuccess()
    {
        $phys = Phys::createNew(new Email('phys@test.com'), new Password('password'));
        $legal = Legal::createNew(new Email('legal@test.com'), new Password('password'));

        Queue::assertNothingPushed();

        try {
            DB::transaction(function () use ($phys, $legal) {
                $this->service->create($phys, $legal, ForWho::PHYS);
                throw new \Exception('rollback');
            });
        } catch (\Throwable $e) {
        }

        $this->assertEquals(0, Redis::connection('default')->llen("queues:{$queueName}"));
    }
}
